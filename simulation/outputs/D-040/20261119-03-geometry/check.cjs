const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('research/agent_native_network/mobile_gateway/studio-model.js','utf8');
const ctx={};vm.createContext(ctx);vm.runInContext(source+'\nthis.S=MobileStudioModel',ctx);
const a={x:100,y:150},b={x:400,y:150};
const straight=ctx.S.pairGeometry(a,b,[],[],29);assert.match(straight.attrs.d,/ L /);
const curve=ctx.S.pairGeometry(a,b,[{x:250,y:150}],[],29);assert.match(curve.attrs.d,/ Q /);
const distance=Math.min(...curve.samples.map(p=>Math.hypot(p.x-250,p.y-150)));assert(distance>=34,`clearance ${distance}`);
const parallel=ctx.S.pairGeometry(a,b,[],[straight.samples],29);assert.match(parallel.attrs.d,/ Q /);
assert(Math.abs(Math.hypot(curve.samples[0].x-a.x,curve.samples[0].y-a.y)-29)<1e-6);
assert(Math.abs(Math.hypot(curve.samples.at(-1).x-b.x,curve.samples.at(-1).y-b.y)-29)<1e-6);
fs.writeFileSync('simulation/outputs/D-040/20261119-03-geometry/RESULT.json',JSON.stringify({status:'passed',straight:straight.attrs.d,curve:curve.attrs.d,parallel:parallel.attrs.d,minimum_obstacle_distance:distance},null,2));
